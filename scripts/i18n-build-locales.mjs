/**
 * Génère es.ts / de.ts à partir de fr.ts + dictionnaires plats.
 * Usage: node scripts/i18n-build-locales.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { createRequire } from "node:module";

const root = path.resolve(import.meta.dirname, "..");
const require = createRequire(import.meta.url);

async function loadFr() {
  const url = pathToFileURL(path.join(root, "src/i18n/messages/fr.ts")).href;
  const mod = await import(url);
  return mod.default;
}

function flat(o, p = "") {
  const out = {};
  for (const [k, v] of Object.entries(o)) {
    const n = p ? `${p}.${k}` : k;
    if (v && typeof v === "object" && !Array.isArray(v)) Object.assign(out, flat(v, n));
    else out[n] = v;
  }
  return out;
}

function setPath(rootObj, pathStr, value) {
  const parts = pathStr.split(".");
  let cur = rootObj;
  for (let i = 0; i < parts.length - 1; i++) {
    cur[parts[i]] ??= {};
    cur = cur[parts[i]];
  }
  cur[parts[parts.length - 1]] = value;
}

function cloneStructure(src) {
  if (Array.isArray(src)) return [...src];
  if (src && typeof src === "object") {
    const out = {};
    for (const [k, v] of Object.entries(src)) out[k] = cloneStructure(v);
    return out;
  }
  return src;
}

function serialize(obj, indent = 0) {
  const pad = "  ".repeat(indent);
  const pad2 = "  ".repeat(indent + 1);
  if (Array.isArray(obj)) {
    const items = obj.map((x) => JSON.stringify(x)).join(", ");
    return `[${items}] as const`;
  }
  if (obj && typeof obj === "object") {
    const lines = Object.entries(obj).map(([k, v]) => {
      const key = /^[a-zA-Z_][a-zA-Z0-9_]*$/.test(k) ? k : JSON.stringify(k);
      return `${pad2}${key}: ${serialize(v, indent + 1)},`;
    });
    return `{\n${lines.join("\n")}\n${pad}}`;
  }
  return JSON.stringify(obj);
}

function writeLocale(lang, header, dict, frTree) {
  const tree = cloneStructure(frTree);
  // Drop `as const` array marker by reassigning from dict
  for (const [k, v] of Object.entries(dict)) setPath(tree, k, v);
  const frKeys = Object.keys(flat(frTree));
  const missing = frKeys.filter((k) => !(k in dict));
  if (missing.length) {
    console.error(`[${lang}] missing ${missing.length} keys:`, missing.slice(0, 20));
    process.exit(1);
  }
  const body = `${header}
const ${lang} = ${serialize(tree)};

export default ${lang} as unknown as import("./fr").MessageTree;
`;
  const out = path.join(root, `src/i18n/messages/${lang}.ts`);
  fs.writeFileSync(out, body);
  console.log(`Wrote ${out} (${frKeys.length} keys)`);
}

